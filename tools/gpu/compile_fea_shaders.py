#!/usr/bin/env python3
# Tisma Slicer: compiles the compute shaders of the structural analysis on the GPU (src/libtisma_fea/src/gpu/*.comp)
# to SPIR-V and writes them as C++ arrays to src/libtisma_fea/src/gpu/FeaShaders.hpp, so that building Tisma does not
# need a shader compiler. Run it after changing a shader; needs glslangValidator (Khronos glslang, package
# "glslang-tools" on Debian / Ubuntu, or the Vulkan SDK).
#
#   python3 tools/gpu/compile_fea_shaders.py
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GPU_DIR = os.path.join(ROOT, 'src', 'libtisma_fea', 'src', 'gpu')
SHADERS = ['fea_apply', 'fea_restrict', 'fea_prolong']


def compile_shader(name):
    src = os.path.join(GPU_DIR, name + '.comp')
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, name + '.spv')
        subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.1', '-o', out, src], check=True,
                       stdout=subprocess.DEVNULL)
        with open(out, 'rb') as f:
            data = f.read()
    assert len(data) % 4 == 0
    return struct.unpack('<%dI' % (len(data) // 4), data)


def main():
    lines = [
        '///|/ Tisma Slicer: SPIR-V of the compute shaders of the structural analysis on the GPU.',
        '///|/ Generated by tools/gpu/compile_fea_shaders.py from src/libtisma_fea/src/gpu/*.comp: do not edit.',
        '///|/',
        '///|/ PrusaSlicer is released under the terms of the AGPLv3 or higher',
        '///|/',
        '#ifndef tisma_fea_gpu_FeaShaders_hpp_',
        '#define tisma_fea_gpu_FeaShaders_hpp_',
        '',
        '#include <cstdint>',
        '',
        'namespace Slic3r {',
        'namespace Fea {',
        'namespace GpuShaders {',
        '',
    ]
    for name in SHADERS:
        words = compile_shader(name)
        lines.append('static const uint32_t %s[] = {' % name)
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
        lines.append('};')
        lines.append('')
    lines += ['} // namespace GpuShaders', '} // namespace Fea', '} // namespace Slic3r', '',
              '#endif // tisma_fea_gpu_FeaShaders_hpp_', '']
    with open(os.path.join(GPU_DIR, 'FeaShaders.hpp'), 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
